package com.usmandev.comparekit.beforeafterslider

/**
 * Controls whether a [BeforeAfterSlider] compares images horizontally or vertically.
 */
enum class SliderOrientation {
    /** Divider moves horizontally; drag left/right to reveal before/after. */
    Horizontal,

    /** Divider moves vertically; drag up/down to reveal before/after. */
    Vertical,
}
